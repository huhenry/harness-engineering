function renderScaffold(result, lang, apply) {
  const lines = [`# ${t('scaffold.title', lang)}`, ''];
  lines.push(t(apply ? 'scaffold.mode.apply' : 'scaffold.mode.dryRun', lang), '');
  if (result.planned.length === 0) {
    lines.push(t('scaffold.noGaps', lang), '');
    return lines.join('\n');
  }
  lines.push(`## ${t('scaffold.planHeading', lang)}`, '');
  lines.push(`| ${t('scaffold.col.action', lang)} | ${t('scaffold.col.target', lang)} | ${t('scaffold.col.gap', lang)} |`);
  lines.push('| --- | --- | --- |');
  for (const p of result.planned) {
    const actionLabel = t(`scaffold.action.${p.action}`, lang);
    lines.push(`| ${actionLabel} | \`${p.target}\` | ${p.gapId} |`);
  }
  lines.push('');
  if (!apply) {
    lines.push(t('scaffold.applyHint', lang), '');
  } else if (result.failure) {
    lines.push(t('scaffold.failure', lang, { target: result.failure.target, message: result.failure.message }), '');
    if (result.written.length > 0) {
      lines.push(t('scaffold.writtenSoFar', lang, { list: result.written.join(', ') }), '');
    }
  }
  return lines.join('\n');
}

function main(argv) {
  const { values, positionals } = parseCli(argv, {
    options: {
      lang: { type: 'string' },
      only: { type: 'string', multiple: true },
      apply: { type: 'boolean', default: false },
      config: { type: 'string' },
    },
    allowPositional: true,
  });
  const repoPath = resolveRepoPath(positionals, process.cwd());
  const ctx = createScanContext(repoPath);
  const lang = assertLang(values.lang ?? loadConfig(ctx, { configPath: values.config }).lang);

  const result = runScaffold({
    repoPath, lang, only: values.only, apply: values.apply, configPath: values.config, now: new Date(),
  });

  process.stdout.write(`${renderScaffold(result, lang, values.apply)}\n`);

  // Spec (task-20-brief-raw.md Interfaces): dry-run always exits 0;
  // an inability to write (or a missing template) exits 1. Mirrors
  // assess.mjs's --min-level / verify.mjs's `report.passed` pattern of
  // returning the gate result rather than throwing it -- a write failure
  // here is an ordinary, expected environment condition (disk full,
  // read-only mount), not the "something in this tool itself broke"
  // case that exit 3 is reserved for.
  return result.failure ? 1 : 0;
}

// Identical to assess.mjs's / verify.mjs's own isMainModule -- see either
// one's full comment for the complete reasoning (symlinked /tmp on macOS,
// spaces/unicode in the path, why pathToFileURL alone still isn't enough).
// Copied verbatim rather than imported: script-entry-point logic, not
// library code that belongs under scripts/lib/.
function isMainModule() {
  if (process.argv[1] === undefined) return false;
  try {
    return fileURLToPath(import.meta.url) === realpathSync(process.argv[1]);
  } catch {
    return false;
  }
}

if (isMainModule()) {
  try {
    process.exit(main(process.argv.slice(2)));
  } catch (err) {
    if (err instanceof CliError) {
      process.stderr.write(`${err.message}\n`);
      process.exit(err.exitCode);
    }
    process.stderr.write(`${err.stack ?? err.message}\n`);
    process.exit(3);
  }
}
